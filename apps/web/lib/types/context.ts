/**
 * Get node type configuration for a specific type within a space
 */
// Legacy/synonym type names that map onto a canonical base type. Keeps nodes
// still stored (or cached) under a retired spelling rendering identically to
// the current one, so un-migrated or stale-cache data never falls through to
// the grey "unknown type" placeholder. Organisations have been through three
// renames now — Organization → Group → Community → Space — so every retired
// spelling lands on `space`.
//
// There is deliberately NO synonym for the old structural 'space' rows
// (sections): 'space' now IS the canonical org type, so those rows can only be
// handled by data migration (scripts/rename-community-to-space.ts) — which is
// why that migration is mandatory, not optional.
//
// `tools` is here for a different reason: it is the note namespace a Tool lives
// in (tools/<name>/index.md), so it is the spelling a member or an agent reaches
// for. Folding it onto `tool` means the plural resolves to the built-in Tool
// type instead of looking like a name nobody has claimed — the same tolerance
// entityKindOf('tools') gives in lib/notes/entities.ts. Both spellings are also
// reserved (lib/types/nodeTypeRegistry.ts), so neither can become a custom type.
const TYPE_SYNONYMS: Record<string, string> = {
  organization: 'space',
  organisation: 'space',
  org: 'space',
  group: 'space',
  groups: 'space',
  company: 'space',
  companies: 'space',
  community: 'space',
  communities: 'space',
  space: 'space',
  spaces: 'space',
  tool: 'tool',
  tools: 'tool',
  model: 'model',
  models: 'model',
};

/**
 * The canonical spelling of a type string: lowercased, with retired names
 * (`org`, `group`, `company`, …) folded onto the type they became. Filtering by
 * raw string instead of this is how a caller ends up matching nothing against
 * legacy rows that still carry the old spelling.
 */
export function canonicalNodeType(type: string | null | undefined): string {
  const normalized = (type ?? '').trim().toLowerCase();
  return TYPE_SYNONYMS[normalized] ?? normalized;
}

/**
 * Every spelling that means the same type as `type` — the canonical one plus
 * any retired synonym for it. For querying stored `node.type` values, which are
 * whatever spelling was current when the row was written.
 */
export function nodeTypeSpellings(type: string | null | undefined): string[] {
  const canonical = canonicalNodeType(type);
  if (!canonical) return [];
  const synonyms = Object.entries(TYPE_SYNONYMS)
    .filter(([, to]) => to === canonical)
    .map(([from]) => from);
  return [...new Set([canonical, ...synonyms])];
}

/**
 * Resolve a type string to a REAL type — one the space configured in its
 * console, or one of the built-in defaults — or null when it is neither.
 *
 * The null arm is the point. `getNodeTypeConfig` below always answers with
 * something so a node is never grey-on-unknown, which is right for nodes: they
 * cannot exist without a type. Free text is a different story. A note's
 * frontmatter can say `type: Note`, `type: Dashboard`, anything at all, and a
 * surface that renders that as a chip is inventing a type the space never
 * created — it looks configured, it isn't, and it can never match a filter,
 * an alias or a colour. Callers showing a type to a user resolve it here first
 * and show nothing when it comes back null.
 */
export function findNodeTypeConfig(
  type: string | null | undefined,
  spaceNodeTypes?: NodeTypeConfig[]
): NodeTypeConfig | null {
  if (!type) return null;
  const normalized = type.trim().toLowerCase();
  if (!normalized) return null;
  const canonical = TYPE_SYNONYMS[normalized] ?? normalized;
  const matches = (t: NodeTypeConfig) => {
    const n = t.name.toLowerCase();
    return n === normalized || n === canonical;
  };
  // The space's own types win: the console is where a type is created, and
  // its name and colour are the ones the rest of the app filters and paints by.
  return spaceNodeTypes?.find(matches) ?? DEFAULT_NODE_TYPES.find(matches) ?? null;
}

export function getNodeTypeConfig(
  type: string,
  spaceNodeTypes?: NodeTypeConfig[]
): NodeTypeConfig {
  const config = findNodeTypeConfig(type, spaceNodeTypes);
  if (config) return config;

  // Truly unknown type — capitalize for display
  return { name: type.charAt(0).toUpperCase() + type.slice(1), color: '#6b7280', shape: 'rectangle' };
}

/**
 * The avatar-fallback glyph a node type should draw when it has no image. People
 * get the person silhouette; spaces and the other containers a cube;
 * events a calendar; resources a document. Tools and models retain recognisable
 * marks when their authored/provider icon is absent, and custom types use a
 * neutral tag mark. A clean SVG-glyph system, not emoji.
 */
export function getNodeGlyph(
  type: string | null | undefined
): 'person' | 'group' | 'event' | 'resource' | 'connector' | 'agent' | 'tool' | 'model' | 'custom' | null {
  if (!type) return null;
  const normalized = type.toLowerCase();
  const canonical = TYPE_SYNONYMS[normalized] ?? normalized;
  if (canonical === 'person' || canonical === 'people') return 'person';
  if (canonical === 'event' || canonical === 'events') return 'event';
  if (canonical === 'resource' || canonical === 'resources') return 'resource';
  // Containers reuse the existing glyphs rather than inventing new ones: a
  // space/section/channel reads as a cube. The glyph key is still called
  // 'group' — it is the shape's name, not a node type.
  if (canonical === 'space' || canonical === 'section' || canonical === 'channel') return 'group';
  if (canonical === 'connector') return 'connector';
  // An agent brief is not a document: it is the thing that runs. Its own glyph
  // is what separates it from the notes it reads and writes.
  if (canonical === 'agent') return 'agent';
  if (canonical === 'tool') return 'tool';
  if (canonical === 'model') return 'model';
  return 'custom';
}

/**
 * Space aliases scoped to a base node type. Matching is case-insensitive
 * because stored node `type` values aren't consistently cased — the canonical
 * way to relate an alias to a node type across the app.
 */
export function aliasesForType(
  aliases: SpaceAlias[] | undefined,
  type: string | null | undefined,
): SpaceAlias[] {
  if (!type) return [];
  const t = type.toLowerCase();
  const canonical = TYPE_SYNONYMS[t] ?? t;
  return (aliases ?? []).filter((a) => {
    const n = a.nodeType.toLowerCase();
    return n === t || n === canonical;
  });
}

/**
 * Find the alias with a given name for a node type (case-insensitive on type).
 * Returns undefined when name is empty or no alias matches.
 */
export function findAlias(
  aliases: SpaceAlias[] | undefined,
  name: string | null | undefined,
  type: string,
): SpaceAlias | undefined {
  if (!name) return undefined;
  return aliasesForType(aliases, type).find((a) => a.name === name);
}

/**
 * The label for a node's type chip. `Node.alias` only counts as a space
 * alias when the space actually configures one by that name for the node's
 * type — events reuse the same column for their public /e/<slug> slug, which
 * must never surface as a type label. Anything unrecognised falls back to the
 * canonical type name ("Event", "Space", …).
 */
export function nodeTypeLabel(
  type: string | null | undefined,
  alias: string | null | undefined,
  aliases: SpaceAlias[] | undefined,
  nodeTypes?: NodeTypeConfig[],
): string {
  const t = type ?? '';
  if (!t) return alias ?? '';
  return findAlias(aliases, alias, t)?.name ?? getNodeTypeConfig(t, nodeTypes).name;
}


// Context domain: nodes, links, node/link type configs, aliases, and their
// canonical defaults + resolution helpers.

// Node type is now dynamic per space
export type NodeType = string;

// Shape options for node rendering
type NodeShape = 'rectangle' | 'hexagon' | 'circle' | 'square';

// Configuration for a node type
export interface NodeTypeConfig {
  name: string; // e.g., "Person", "Organization"
  color: string; // Hex color e.g., "#2563eb"
  shape: NodeShape; // Shape to render
  /**
   * `note` marks a type a member invented from the draft surface. Things made
   * under it are plain context notes — Context and Raw, a coloured type chip,
   * no profile page — because nothing syncs a graph node for a note. Surfaces
   * that list types in order to FILTER NODES skip these; surfaces that label or
   * colour a type show them like any other. Absent on the built-ins, which a
   * tool claims and turns into real directory entities.
   */
  scope?: 'note';
  /**
   * What to call a SET of these, when the English rule in lib/types/plural.ts
   * gets the name wrong. Absent on every type whose plural is derivable, which
   * is nearly all of them — the surfaces that name a set (the Directory's
   * tables, the Type filter, a folder index's headings) read
   * `pluralTypeName`, never this field directly.
   */
  plural?: string;
  /**
   * A type every space has by default that is not a directory record: it
   * labels a place or a tool's config (a folder, a room, an agent), never
   * something the Grid shows, and carries no aliases. Console → Types does not
   * list it. Only the built-ins set it, so ask {@link isHiddenNodeType} rather
   * than a stored row, which may predate the flag.
   */
  hidden?: true;
  /**
   * What this type TRACKS, beyond the rows every entity of it already carries
   * (lib/create/typeFields.ts): the columns the Directory's table shows for
   * it, and the properties an agent can read off its entity note. Each
   * field's value lives at `node.metadata[key]` and is mirrored into the
   * entity note's frontmatter under the same key. Admin-authored
   * (lib/directory/table.ts#addTrackedField); absent on a type nobody has
   * extended.
   */
  fields?: TrackedField[];
}

/** The value shapes a tracked field can take — what the cell editor renders. */
export type TrackedFieldKind = 'text' | 'number' | 'date' | 'url' | 'email' | 'select' | 'checkbox';

/** One thing a space decided to track about a type. */
export interface TrackedField {
  /** Metadata key: `[a-z][a-z0-9_]*`, unique within the type, never a key the platform owns. */
  key: string;
  label: string;
  kind: TrackedFieldKind;
  /** The choices of a `select` field. */
  options?: string[];
}


// A named alias with a display color, scoped to a specific node type within a
// space. Created on the Types page — and for the Person type they are also
// the space's PERMISSION model: a member holds any number of their Person
// aliases (UserAlias rows), `admin` says holders manage the space, and a
// ContextGrant with subjectType 'alias' targets one by name. So "Engineering" is
// one thing: a chip in the directory and a set of permissions.
export interface SpaceAlias {
  /** Stable identity, independent of the name. Everything that stores a
   *  reference to an alias — holders, grants, directory chips — points at this,
   *  so renaming is a single write to this array and nothing else can desync.
   *  Optional only for entries seeded before ids existed; `aliasKey` in
   *  lib/spaces/configMerge.ts is the one place that falls back to the name. */
  id?: string;
  name: string;    // e.g. "Founder"
  color: string;   // Hex color e.g. "#16a34a"
  nodeType: string; // e.g. "Person", "Space"
  // Person aliases only
  /** Holders manage the space (lib/auth.ts#isAdmin). */
  admin?: boolean;
  /** The built-in Admin alias — like the system link types, it can't be removed
   *  or recoloured, and it always is admin of the space. */
  system?: boolean;
}

/** The built-in Person alias every space has. Gold, fixed, always owns. */
export const ADMIN_ALIAS_NAME = 'Admin';
/**
 * Admin's id is a reserved constant rather than a generated one, because most
 * spaces never store the alias at all — `personAliases` grafts it in. A
 * generated id would differ per space and per graft, so the one alias every
 * space is guaranteed to have would be the one nothing could point at.
 */
export const ADMIN_ALIAS_ID = 'admin';
export const ADMIN_ALIAS: SpaceAlias = {
  id: ADMIN_ALIAS_ID,
  name: ADMIN_ALIAS_NAME,
  color: '#b4881b',
  nodeType: 'Person',
  admin: true,
  system: true,
};

/**
 * A space's Person aliases — its permission vocabulary. The built-in Admin
 * alias is grafted in first whether or not it is stored, so a space can
 * never present itself as having nothing that owns it.
 */
export function personAliases(aliases: SpaceAlias[] | undefined): SpaceAlias[] {
  const stored = aliasesForType(aliases, 'Person').filter((a) => a.name !== ADMIN_ALIAS_NAME);
  const admin = aliasesForType(aliases, 'Person').find((a) => a.name === ADMIN_ALIAS_NAME);
  // Admin's id is fixed even if a stored entry somehow carries another one:
  // holders and grants recorded against `admin` must never stop resolving.
  return [{ ...ADMIN_ALIAS, ...admin, id: ADMIN_ALIAS_ID, admin: true, system: true }, ...stored];
}

/**
 * The Person aliases someone may pick for THEMSELVES when joining a space.
 *
 * Never an admin one. Managing a space is something the space hands out from
 * the console, so the door must not offer it, and the filter is on the `admin`
 * flag rather than the built-in Admin's name so a space that calls its owning
 * alias "Owner" is covered too.
 */
export function selfJoinAliases(aliases: SpaceAlias[] | undefined): SpaceAlias[] {
  return personAliases(aliases).filter((a) => !a.admin && !a.system);
}

/**
 * Resolve an alias from whatever a caller has: its id, or its name.
 *
 * Storage keys on the id, but the id is internal — the console, the API and the
 * MCP tools all speak names, because a name is what a person (or an agent
 * reading a directory card) actually knows. This is the one place that
 * translation happens, so every entry point gets the same rules: an exact id
 * match first, then a name match that ignores case and surrounding space. That
 * casing tolerance is deliberate — `alias: "founder"` against a vocabulary
 * holding `"Founder"` used to be stored verbatim and then matched nothing.
 *
 * `type` narrows to one node type's vocabulary; omit it to search all of them.
 */
export function findAliasByRef(
  aliases: SpaceAlias[] | undefined,
  ref: string | null | undefined,
  type?: string,
): SpaceAlias | undefined {
  if (!ref) return undefined;
  const pool = type
    ? canonicalNodeType(type) === 'person'
      ? personAliases(aliases)
      : aliasesForType(aliases, type)
    : (aliases ?? []);
  const byId = pool.find((a) => a.id === ref);
  if (byId) return byId;
  const key = ref.trim().toLowerCase();
  return pool.find((a) => a.name?.trim().toLowerCase() === key);
}


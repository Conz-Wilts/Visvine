// Where a Link came from. `manual` = created in the UI by an admin; the rest are
// system-generated by an action (and carry `originRef` for symmetric auto-undo);
// `context` = derived from an entity mention in a context note (originRef = the
// note path); `structure` = the containment edge from a space to its sections,
// channels, notes and files (originRef = the child node id, so moving or deleting
// the child undoes exactly its own edge); `import` = bulk-loaded curated data.
export type LinkOrigin =
  | 'manual'
  | 'event_attendance'
  | 'event_hosting'
  | 'intro'
  | 'context'
  | 'structure'
  | 'import';


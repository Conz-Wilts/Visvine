/**
 * Is this one of the built-in types that is in every space and never a Grid
 * record ({@link NodeTypeConfig.hidden})? Read from the built-ins, not the
 * space's stored row, so a vocabulary saved before the flag existed agrees.
 */
export function isHiddenNodeType(name: string | null | undefined): boolean {
  const key = (name ?? '').trim().toLowerCase();
  return DEFAULT_NODE_TYPES.some((t) => t.hidden && t.name.toLowerCase() === key);
}

// Aliases are entirely space-configured — there is no built-in list for any
// type, Connector included. A connector's `alias: http` frontmatter picks its
// executor on its own (lib/connectors/config.ts never reads this registry), so
// the alias rows here are pure display vocabulary and an admin owns all of them:
// add, recolour, remove.

/**
 * Node types that describe where things live rather than who/what they are.
 * These are hidden by default in the context view and excluded from the
 * directory grid; the type filter turns them back on. Lowercase — compare
 * against a node's stored `type`, which is canonicalised lowercase on write.
 *
 * `space` (the org type) is deliberately NOT here. It
 * carries the organisations that used to be the Group type, which are
 * directory records people expect to see; the cost is that a space's own root
 * node shows up in its grid too, which reads as a "this space" card and links
 * to /spaces/<id>.
 *
 * `note`, `file` and `index` are listed so they stay out of the grid and the
 * graph. `index` is a live entry in the vocabulary — it is what a folder's chip
 * is coloured by — but never a node: a folder is a path, and its `type:` is
 * still stripped on write (lib/notes/shared/indexNote.ts).
 */
export const STRUCTURAL_NODE_TYPES: readonly string[] = [
  'section',
  'channel',
  'note',
  'file',
  'index',
  'subspace',
  'connector',
  'agent',
  'tool',
];

/**
 * The graph node standing for a space itself.
 *
 * Space ids are usually already `space:`-prefixed (`space:blackbird`
 * from the slugified name), so prefixing blindly would produce
 * `space:space:blackbird` — and, worse, a note path with a colon in it,
 * because entityNotePath slugs everything after the FIRST colon. Normalising
 * here keeps the id and the note path (`spaces/blackbird.md`) clean whether
 * or not the caller's id carries the prefix.
 *
 * Lives here rather than in lib/notes/context/entityNodes.ts (which re-exports it)
 * because client components need it and that module imports prisma.
 */
export function spaceNodeId(spaceId: string): string {
  return `space:${spaceId.replace(/^space:/, '')}`;
}

/**
 * Does this `space`-typed node stand for the space it lives in, or for a
 * group/organisation recorded inside it?
 *
 * Both wear `type: 'space'` and (for legacy rows) a `space:<slug>` id —
 * ids are opaque and keep whatever prefix they were minted with across the
 * type's renames (Group → Community → Space). The space's own root node is
 * the one whose id derives from its own `spaceId`; anything else is a
 * card pointing at some other space (see `metadata.spaceRef`).
 *
 * This is the discriminator every consumer needs: the root node redirects to
 * /spaces/<id>, a record renders its profile in place, and only records
 * resolve to a cross-space organisation Identity.
 */
export function isOwnSpaceNode(node: { id: string; spaceId?: string | null }): boolean {
  if (!node.spaceId) return false;
  return spaceNodeId(node.spaceId) === node.id;
}

/** Whether a node type is structural (see {@link STRUCTURAL_NODE_TYPES}). */
export function isStructuralNodeType(type: string | null | undefined): boolean {
  if (!type) return false;
  const normalized = type.toLowerCase();
  return STRUCTURAL_NODE_TYPES.includes(TYPE_SYNONYMS[normalized] ?? normalized);
}

